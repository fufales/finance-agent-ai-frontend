export const exportToCSV = (data) => {
  const rows = [];
  
  // Headers
  rows.push(['Type', 'ID', 'Name', 'Amount', 'Category/Type', 'Period', 'Date', 'Paid', 'Color'].join(','));

  // Income
  if (data.income) {
    if (data.income.period1) {
      rows.push(['Income', 'income-p1', 'Period 1 Income', data.income.period1, 'Income', '1', '', '', ''].join(','));
    }
    if (data.income.period2) {
      rows.push(['Income', 'income-p2', 'Period 2 Income', data.income.period2, 'Income', '2', '', '', ''].join(','));
    }
  }

  // Expenses
  if (data.expenses && data.expenses.length > 0) {
    data.expenses.forEach(expense => {
      rows.push([
        'Expense',
        expense.id,
        `"${expense.name.replace(/"/g, '""')}"`, // Escape quotes
        expense.amount,
        expense.category,
        expense.period,
        expense.date,
        expense.paid,
        ''
      ].join(','));
    });
  }

  // Funds
  if (data.funds && data.funds.length > 0) {
    data.funds.forEach(fund => {
      rows.push([
        'Fund',
        fund.id,
        `"${fund.name.replace(/"/g, '""')}"`,
        fund.amount,
        fund.type,
        fund.period || '',
        '',
        '',
        fund.color
      ].join(','));
    });
  }

  return rows.join('\n');
};

export const parseCSV = (csvText) => {
  const lines = csvText.split('\n');
  const data = {
    income: { period1: 0, period2: 0 },
    expenses: [],
    funds: []
  };

  // Skip header
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    // Handle quoted strings properly (simple regex split won't work for commas inside quotes)
    // This is a simple parser assuming standard CSV format generated by exportToCSV
    // Clean up quotes
    const values = line.split(',').map(val => {
        val = val.trim();
        if (val.startsWith('"') && val.endsWith('"')) {
            return val.slice(1, -1).replace(/""/g, '"');
        }
        return val;
    });
    
    // Simple split fallback if regex fails or for simple lines
    // Note: A robust CSV parser library is better, but for this scope we'll do a manual split 
    // taking care of the specific format we generate.
    // Let's use a slightly more robust manual parse since we control the format.
    
    const type = values[0];
    
    if (type === 'Income') {
      const period = values[5];
      const amount = parseFloat(values[3]);
      if (period === '1') data.income.period1 = amount;
      if (period === '2') data.income.period2 = amount;
    } else if (type === 'Expense') {
      data.expenses.push({
        id: values[1],
        name: values[2],
        amount: parseFloat(values[3]),
        category: values[4],
        period: parseInt(values[5]),
        date: values[6],
        paid: values[7] === 'true'
      });
    } else if (type === 'Fund') {
      data.funds.push({
        id: values[1],
        name: values[2],
        amount: parseFloat(values[3]),
        type: values[4],
        period: values[5] ? parseInt(values[5]) : null,
        color: values[8]
      });
    }
  }

  return data;
};
