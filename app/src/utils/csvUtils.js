export const exportToCSV = (data) => {
  const rows = [];
  
  // Headers
  rows.push(['Type', 'ID', 'Name', 'Amount', 'Category/Type', 'Period', 'Date', 'Paid', 'Color', 'RemainingAmount'].join(','));

  // Income
  if (data.income) {
    if (data.income.period1) {
      rows.push(['Income', 'income-p1', 'Period 1 Income', data.income.period1, 'Income', '1', '', '', '', ''].join(','));
    }
    if (data.income.period2) {
      rows.push(['Income', 'income-p2', 'Period 2 Income', data.income.period2, 'Income', '2', '', '', '', ''].join(','));
    }
  }

  // Expenses
  if (data.expenses && data.expenses.length > 0) {
    data.expenses.forEach(expense => {
      rows.push([
        'Expense',
        expense.id,
        `"${expense.name.replace(/"/g, '""')}"`, // Escape quotes
        expense.amount,
        expense.category,
        expense.period,
        expense.date,
        expense.paid,
        '',
        ''
      ].join(','));
    });
  }

  // Funds
  if (data.funds && data.funds.length > 0) {
    data.funds.forEach(fund => {
      rows.push([
        'Fund',
        fund.id,
        `"${fund.name.replace(/"/g, '""')}"`,
        fund.amount,
        fund.type,
        fund.period || '',
        '',
        '',
        fund.color,
        ''
      ].join(','));
    });
  }

  // Goals
  if (data.goals && data.goals.length > 0) {
    data.goals.forEach(goal => {
      rows.push([
        'Goal',
        goal.id,
        `"${goal.name.replace(/"/g, '""')}"`,
        goal.totalAmount, // Map totalAmount to Amount column
        goal.category,
        '', // Period
        '', // Date
        '', // Paid
        '', // Color
        goal.remainingAmount
      ].join(','));
    });
  }

  // DashboardConfig
  if (data.dashboardConfig) {
    rows.push([
        'DashboardConfig',
        '', // ID
        '', // Name
        '', // Amount
        '', // Category
        '', // Period
        '', // Date
        data.dashboardConfig.showPaid, // using 'Paid' column for showPaid boolelan
        JSON.stringify(data.dashboardConfig), // storing full json in Color column as a backup/easier parsing if needed, but let's map individual fields to be cleaner if possible.
        // Actually, let's just use a specific row format for config or reuse columns.
        // Let's use: Type=DashboardConfig, Paid=showPaid, Period=showIncome, Date=showDebtPercentage, Color=showDebtAmount
        // But wait, boolean string "true"/"false" is fine.
        // Paid col is index 7.
        // Let's use:
        // Col 7 (Paid): showPaid
        // Col 5 (Period): showIncome (as string "true"/"false") - wait Period is index 5
        // Let's just put a JSON string in the last column or Spread them.
        // Let's try to map to existing columns to keep CSV structure "consistent" (same number of columns).
        // Type, ID, Name, Amount, Category, Period, Date, Paid, Color, RemainingAmount
        // DashboardConfig, - , -, -, -, showIncome, showDebtPercentage, showPaid, showDebtAmount, -
        // Let's use: 
        // Paid (7): showPaid
        // Period (5): showIncome
        // Date (6): showDebtPercentage
        // Color (8): showDebtAmount
        '' 
    ].join(','));
  }

  return rows.join('\n');
};

export const parseCSV = (csvText) => {
  const lines = csvText.split('\n');
  const data = {
    income: { period1: 0, period2: 0 },
    expenses: [],
    funds: [],
    goals: []
  };

  // Skip header
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    // Handle quoted strings properly (simple regex split won't work for commas inside quotes)
    // This is a simple parser assuming standard CSV format generated by exportToCSV
    // Clean up quotes
    const values = line.split(',').map(val => {
        val = val.trim();
        if (val.startsWith('"') && val.endsWith('"')) {
            return val.slice(1, -1).replace(/""/g, '"');
        }
        return val;
    });
    
    // Simple split fallback if regex fails or for simple lines
    // Note: A robust CSV parser library is better, but for this scope we'll do a manual split 
    // taking care of the specific format we generate.
    // Let's use a slightly more robust manual parse since we control the format.
    
    const type = values[0];
    
    if (type === 'Income') {
      const period = values[5];
      const amount = parseFloat(values[3]);
      if (period === '1') data.income.period1 = amount;
      if (period === '2') data.income.period2 = amount;
    } else if (type === 'Expense') {
      data.expenses.push({
        id: values[1],
        name: values[2],
        amount: parseFloat(values[3]),
        category: values[4],
        period: parseInt(values[5]),
        date: values[6],
        paid: values[7] === 'true'
      });
    } else if (type === 'Fund') {
      data.funds.push({
        id: values[1],
        name: values[2],
        amount: parseFloat(values[3]),
        type: values[4],
        period: values[5] ? parseInt(values[5]) : null,
        color: values[8]
      });
    } else if (type === 'Goal') {
      data.goals.push({
        id: values[1],
        name: values[2],
        totalAmount: parseFloat(values[3]),
        category: values[4],
        remainingAmount: parseFloat(values[9])
      });
    } else if (type === 'DashboardConfig') {
        data.dashboardConfig = {
            showPaid: values[7] === 'true',
            showIncome: values[5] === 'true',
            showDebtPercentage: values[6] === 'true',
            showDebtAmount: values[8] === 'true'
        };
    }
  }

  return data;
};
